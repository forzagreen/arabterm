"""Export arabterm.db as a Hugging Face dataset, and optionally push it.

    uv run --env-file .env python arabterm/scripts/export_hf.py [--push]
        [--repo forzagreen/arabterm] [--message "..."]

Writes to hf/ (gitignored) at the repo root:
    hf/README.md                  the dataset card, from hf_dataset_card.md
    hf/data/terms.parquet         one row per term, with the dictionary slug
    hf/data/dictionaries.parquet  one row per dictionary

With --push, uploads those files to the dataset repo on the Hub (creating it
if needed). The token comes from HF_TOKEN. GitHub stays canonical: this is a
mirror, regenerated by .github/workflows/publish-huggingface.yml whenever
arabterm.db.gz changes on main.
"""

from __future__ import annotations

import argparse
import os
import subprocess
import sys
from datetime import date, datetime
from pathlib import Path
from string import Template

import pyarrow as pa
import pyarrow.parquet as pq
from sqlalchemy import text

from arabterm.scripts.update_readme import _en_fr_cell, _wikidata_cell
from arabterm.sqlite_models import get_sqlite_connection

REPO_ROOT = Path(__file__).resolve().parents[2]
OUT_DIR = REPO_ROOT / "hf"
CARD_TEMPLATE = Path(__file__).with_name("hf_dataset_card.md")
DEFAULT_REPO = "forzagreen/arabterm"
BATCH_SIZE = 50_000

DICTIONARY_COLUMNS = [
    "id",
    "name_tech",
    "name_arabic",
    "name_english",
    "name_french",
    "nbr_entries",
    "dict_type",
    "tier",
    "wikidata_id",
    "archive_org_url",
    "page_offset",
    "created_at",
    "updated_at",
]
TERM_COLUMNS = [
    "id",
    "arabic",
    "english",
    "french",
    "description",
    "dictionary_id",
    "dictionary",
    "page",
    "uri",
    "created_at",
    "updated_at",
]
TIMESTAMP = pa.timestamp("us")
INT = pa.int64()
STR = pa.string()
DICTIONARY_SCHEMA = pa.schema(
    [
        ("id", INT),
        ("name_tech", STR),
        ("name_arabic", STR),
        ("name_english", STR),
        ("name_french", STR),
        ("nbr_entries", INT),
        ("dict_type", STR),
        ("tier", INT),
        ("wikidata_id", STR),
        ("archive_org_url", STR),
        ("page_offset", INT),
        ("created_at", TIMESTAMP),
        ("updated_at", TIMESTAMP),
    ]
)
TERM_SCHEMA = pa.schema(
    [
        ("id", INT),
        ("arabic", STR),
        ("english", STR),
        ("french", STR),
        ("description", STR),
        ("dictionary_id", INT),
        ("dictionary", STR),
        ("page", INT),
        ("uri", STR),
        ("created_at", TIMESTAMP),
        ("updated_at", TIMESTAMP),
    ]
)

DICTIONARY_SQL = f"""
    SELECT {", ".join(DICTIONARY_COLUMNS)} FROM dictionary ORDER BY id
"""
TERM_SQL = """
    SELECT t.id, t.arabic, t.english, t.french, t.description,
           t.dictionary_id, d.name_tech AS dictionary, t.page, t.uri,
           t.created_at, t.updated_at
    FROM term t JOIN dictionary d ON d.id = t.dictionary_id
    ORDER BY t.id
"""


def _timestamp(value) -> datetime | None:
    """SQLite stores naive UTC text, with or without fractional seconds."""
    if value is None or value == "":
        return None
    if isinstance(value, datetime):
        return value
    return datetime.fromisoformat(str(value))


def _column(values: list, field: pa.Field) -> pa.Array:
    if field.type == TIMESTAMP:
        values = [_timestamp(v) for v in values]
    return pa.array(values, type=field.type)


def _write_parquet(connection, sql: str, schema: pa.Schema, path: Path) -> int:
    """Stream the query into a Parquet file in batches; returns the row count."""
    path.parent.mkdir(parents=True, exist_ok=True)
    result = connection.execution_options(stream_results=True).execute(text(sql))
    rows_written = 0
    with pq.ParquetWriter(path, schema, compression="zstd") as writer:
        while rows := result.fetchmany(BATCH_SIZE):
            columns = list(zip(*rows))
            batch = pa.record_batch(
                [_column(list(col), schema.field(i)) for i, col in enumerate(columns)],
                schema=schema,
            )
            writer.write_batch(batch)
            rows_written += len(rows)
    return rows_written


def _count(connection, table: str) -> int:
    return connection.execute(text(f"SELECT count(*) FROM {table}")).scalar_one()


def _dictionaries_table(connection) -> str:
    """Markdown table of the dictionaries, with the slug used in `dictionary`."""
    rows = connection.execute(
        text(
            "SELECT name_tech, name_arabic, name_english, name_french, "
            "nbr_entries, wikidata_id FROM dictionary "
            "ORDER BY created_at DESC, id DESC"
        )
    ).all()
    lines = [
        "| `dictionary` | العربية | English / Français | Terms | Wikidata |",
        "|:---|:---|:---|---:|:---:|",
    ]
    for slug, ar, en, fr, n, qid in rows:
        lines.append(
            f"| `{slug}` | {(ar or '').strip()} | {_en_fr_cell(en, fr)} "
            f"| {n or 0} | {_wikidata_cell(qid)} |"
        )
    return "\n".join(lines)


def _commit_sha() -> str:
    sha = os.environ.get("GITHUB_SHA")
    if not sha:
        try:
            sha = subprocess.run(
                ["git", "rev-parse", "HEAD"],
                cwd=REPO_ROOT,
                capture_output=True,
                text=True,
                check=True,
            ).stdout.strip()
        except (OSError, subprocess.CalledProcessError):
            sha = ""
    return sha


def _render_card(connection, n_terms: int, n_dictionaries: int) -> str:
    sha = _commit_sha()
    if sha:
        source = f"[`{sha[:7]}`](https://github.com/forzagreen/arabterm/commit/{sha})"
    else:
        source = "an uncommitted working copy"
    template = Template(CARD_TEMPLATE.read_text(encoding="utf-8"))
    return template.substitute(
        n_terms=n_terms,
        n_dictionaries=n_dictionaries,
        dictionaries_table=_dictionaries_table(connection),
        exported_from=source,
        exported_on=date.today().isoformat(),
    )


def export() -> None:
    with get_sqlite_connection() as session:
        connection = session.connection()
        n_dictionaries = _write_parquet(
            connection,
            DICTIONARY_SQL,
            DICTIONARY_SCHEMA,
            OUT_DIR / "data" / "dictionaries.parquet",
        )
        n_terms = _write_parquet(
            connection, TERM_SQL, TERM_SCHEMA, OUT_DIR / "data" / "terms.parquet"
        )
        expected = (_count(connection, "dictionary"), _count(connection, "term"))
        if (n_dictionaries, n_terms) != expected:
            raise SystemExit(
                f"row count mismatch: wrote {n_dictionaries} dictionaries and "
                f"{n_terms} terms, the database has {expected[0]} and {expected[1]}"
            )
        card = _render_card(connection, n_terms, n_dictionaries)
    (OUT_DIR / "README.md").write_text(card, encoding="utf-8")
    print(f"Wrote {n_dictionaries} dictionaries and {n_terms} terms to {OUT_DIR}")


def push(repo: str, message: str) -> None:
    token = os.environ.get("HF_TOKEN")
    if not token:
        sys.exit(
            "HF_TOKEN is not set: put a write token from "
            "https://huggingface.co/settings/tokens in .env"
        )
    from huggingface_hub import HfApi

    api = HfApi(token=token)
    api.create_repo(repo, repo_type="dataset", exist_ok=True)
    api.upload_folder(
        repo_id=repo,
        repo_type="dataset",
        folder_path=OUT_DIR,
        path_in_repo=".",
        allow_patterns=["README.md", "data/*.parquet"],
        commit_message=message,
    )
    print(f"Pushed to https://huggingface.co/datasets/{repo}")


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__.split("\n\n")[0])
    parser.add_argument("--push", action="store_true", help="upload hf/ to the Hub")
    parser.add_argument("--repo", default=DEFAULT_REPO, help="Hub dataset repo id")
    parser.add_argument(
        "--message", default="Update from arabterm", help="Hub commit message"
    )
    args = parser.parse_args()
    export()
    if args.push:
        push(args.repo, args.message)


if __name__ == "__main__":
    main()
